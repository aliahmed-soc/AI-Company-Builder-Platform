#!/usr/bin/env node
// ACBP — render the failure-scenario evidence document FROM the index (ACBP-P7-008; CDR-084 §6).
//
// WHY THIS IS GENERATED AND NOT WRITTEN. CDR-084 §6 rules that the index IS the evidence artefact, and that the
// human-readable version must be rendered from it: "no separate folder of screenshots or logs — those are the
// artefact class ACBP-P7-002 proved unreliable, because nothing checks them."
//
// A hand-written summary of a machine-checked table is a second copy of the truth that nothing keeps honest.
// This repository has already paid for that twice: ACBP-P7-002's artefacts asserted a control nobody had built,
// and ACBP-P7-007's ledger opened with "THE TICKET IS NOT DONE AND IS NOT MERGED" — true when written, false
// the moment it merged, and it took a review pass to notice.
//
// So the document has no independent existence. `--check` re-renders and compares; any edit to the .md, or any
// change to the index without re-rendering, fails the build. `pnpm run docs:scenario-evidence` regenerates it.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = process.cwd();
const OUT = join(ROOT, 'docs', 'implementation', 'P7-008-SCENARIO-EVIDENCE.md');
const INDEX = join(ROOT, 'tools', 'failure-scenario-index.mjs');

/** `|` inside a cell would end the column early; a newline would end the row. */
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ').trim();

const STATUS_MARK = Object.freeze({
  measured: '**MEASURED**',
  unmeasured: 'unmeasured',
  absent: 'absent',
  unbuildable: 'unbuildable',
});

/**
 * @param {{FAILURE_SCENARIO_INDEX: readonly object[], MAX_UNPROVEN: number}} mod
 * @returns {string} the complete document
 */
export function renderEvidence(mod) {
  const rows = mod.FAILURE_SCENARIO_INDEX;
  const measured = rows.filter((r) => r.status === 'measured');
  const noSubject = rows.filter((r) => r.status === 'absent' || r.status === 'unbuildable');
  const unmeasured = rows.filter((r) => r.status === 'unmeasured');

  const out = [];
  out.push('# ACBP-P7-008 — failure-scenario evidence');
  out.push('');
  out.push('<!-- GENERATED FROM tools/failure-scenario-index.mjs BY tools/render-scenario-evidence.mjs.');
  out.push('     DO NOT EDIT THIS FILE. Edit the index and run `pnpm run docs:scenario-evidence`.');
  out.push('     `pnpm run check:scenario-evidence` fails the build when the two disagree. -->');
  out.push('');
  out.push(
    'This document is **rendered from the machine-checked index**, per CDR-084 §6, so it cannot drift from it. ' +
      'The index is the evidence artefact; this is a reading of it.',
  );
  out.push('');
  out.push('## What "green" means here');
  out.push('');
  out.push(
    'A row is GREEN only when a test **injects** the failure at a production entry point, asserts **that row\'s own ' +
      'documented consequence**, and a **recorded mutation made that test go red in a hosted CI run**. A passing ' +
      'test that nobody has tried to break is `unmeasured`, in that word — not green.',
  );
  out.push('');
  out.push(`- **${measured.length} of ${rows.length} MEASURED** — a recorded run id says the cited test can fail.`);
  out.push(`- **${unmeasured.length} unmeasured** — a live test exists and passes; nothing has proved it can fail.`);
  out.push(`- **${noSubject.length} with no injectable subject** — the failure has no entity in this system. See each row.`);
  out.push(`- Ceiling on not-yet-measured rows: **${mod.MAX_UNPROVEN}**, compared against \`origin/main\` so it cannot rise.`);
  out.push('');
  out.push('## Two limits of this evidence, stated up front');
  out.push('');
  out.push(
    '1. **A run id is shape-checked, never resolved.** Nothing here contacts GitHub, so a hand-typed number ' +
      'passes the gate. `gh run view <id>` is what actually resolves it, and that is a human step (CDR-080 §7.10).',
  );
  out.push(
    '2. **Nothing machine-checks a mutation against the test title it claims to redden.** The mutation must name ' +
      'real code — that IS enforced — but a real symbol aimed at the wrong control still passes (CDR-080 §7.11).',
  );
  out.push('');
  out.push('## The sixteen rows');
  out.push('');
  out.push('| # | Failure | Status | Anchor | Consequence asserted | Injection seam | Entry point |');
  out.push('|---:|---|---|---|---|---|---|');
  for (const r of rows) {
    out.push(
      `| ${r.number} | ${cell(r.failure)} | ${STATUS_MARK[r.status] ?? cell(r.status)} | \`${cell(r.anchor)}\` | ` +
        `${cell(r.consequence) || '—'} | ${cell(r.injection) || '—'} | ${cell(r.entryPoint) || '—'} |`,
    );
  }
  out.push('');
  out.push('## Per row: what proves it, and what it does not prove');
  out.push('');
  for (const r of rows) {
    out.push(`### ${r.number}. ${cell(r.failure)} — ${STATUS_MARK[r.status] ?? r.status}`);
    out.push('');
    if (r.file) {
      out.push(`- **Test:** \`${cell(r.file)}\``);
      out.push(`  - "${cell(r.testTitle)}"`);
    } else {
      out.push('- **Test:** none. This row cites no test, deliberately — see below.');
    }
    if (r.mutation) out.push(`- **Mutation that should redden it:** ${cell(r.mutation)}`);
    out.push(`- **Hosted CI run in which it did:** ${r.mutationRunId ? `\`${cell(r.mutationRunId)}\`` : '— *(not yet run)*'}`);
    out.push(`- **Does not prove:** ${cell(r.doesNotProve)}`);
    if (r.notes) out.push(`- **Verification note:** ${cell(r.notes)}`);
    out.push('');
  }
  out.push('---');
  out.push('');
  out.push(
    'Sources: `tools/failure-scenario-index.mjs` (the index), `tools/check-failure-scenario-index.mjs` (the gate), ' +
      '`docs/architecture/FAILURE-AND-RECOVERY.md` (the canon matrix), CDR-084 (the decisions).',
  );
  out.push('');
  return out.join('\n');
}

const invokedDirectly =
  typeof process.argv[1] === 'string' && import.meta.url === pathToFileURL(resolve(process.argv[1])).href;
if (invokedDirectly) await main();

async function main() {
  const checkOnly = process.argv.includes('--check');
  if (!existsSync(INDEX)) {
    console.error(`✖ scenario-evidence render CANNOT SEE ITS SOURCE: ${INDEX} is missing.`);
    process.exit(2);
  }
  const mod = await import(pathToFileURL(INDEX).href);
  const rendered = renderEvidence(mod);

  if (!checkOnly) {
    writeFileSync(OUT, rendered, 'utf8');
    console.log(`✔ rendered ${mod.FAILURE_SCENARIO_INDEX.length} rows → docs/implementation/P7-008-SCENARIO-EVIDENCE.md`);
    return;
  }

  if (!existsSync(OUT)) {
    console.error('✖ docs/implementation/P7-008-SCENARIO-EVIDENCE.md is MISSING. Run `pnpm run docs:scenario-evidence`.');
    process.exit(1);
  }
  const onDisk = readFileSync(OUT, 'utf8');
  if (onDisk !== rendered) {
    console.error('✖ docs/implementation/P7-008-SCENARIO-EVIDENCE.md is OUT OF STEP with the index it is generated from.');
    console.error('  Either the index changed without re-rendering, or the document was edited by hand.');
    console.error('  It is generated on purpose: a hand-written summary of a checked table is a second copy of the');
    console.error('  truth that nothing keeps honest. Run `pnpm run docs:scenario-evidence`.');
    process.exit(1);
  }
  console.log(`✔ scenario evidence document matches the index (${mod.FAILURE_SCENARIO_INDEX.length} rows).`);
}
